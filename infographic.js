  // 7. Decibel Meter Engine ("UNLEASH THE ROAR" · 80 dB to 125+ dB)
  const roarBtn = document.querySelector('#roar-trigger-btn');
  const dbValueEl = document.querySelector('#decibel-value');
  const dbTierEl = document.querySelector('#decibel-tier');
  const dbRingEl = document.querySelector('#decibel-ring');
  const dbEngineCard = document.querySelector('#decibel-engine');
  if (roarBtn && dbValueEl && dbTierEl && dbRingEl && dbEngineCard) {
    let db = 80;
    let holding = false;
    let rafId = null;
    function renderDb() {
      const pct = Math.min(100, Math.max(0, ((db - 80) / 45) * 100));
      dbValueEl.textContent = `${Math.round(db)} dB`;
      dbRingEl.style.setProperty('--roar-pct', `${pct.toFixed(1)}%`);
      dbRingEl.style.transform = `scale(${(1 + pct * 0.0038).toFixed(3)})`;
      if (db >= 122) {
        dbTierEl.textContent = '125 dB PEAK CHINNASWAMY ROAR! ROOF SHAKING!';
        dbEngineCard.classList.add('roar-shake');
      } else if (db >= 108) {
        dbTierEl.textContent = '110+ dB · "R-C-B! R-C-B!" STADIUM SURGE';
        dbEngineCard.classList.remove('roar-shake');
      } else if (db > 84) {
        dbTierEl.textContent = 'BUILDING THE CHANT ACROSS BENGALURU…';
        dbEngineCard.classList.remove('roar-shake');
      } else {
        dbTierEl.textContent = '80 dB AMBIENT CROWD · PRESS & HOLD TO UNLEASH THE ROAR';
        dbEngineCard.classList.remove('roar-shake');
      }
    }
    function stepRoar() {
      if (holding) {
        db = Math.min(125, db + 0.85);
      } else {
        db = Math.max(80, db - 0.65);
      }
      renderDb();
      if (holding || db > 80) {
        rafId = requestAnimationFrame(stepRoar);
      } else {
        rafId = null;
      }
    }
    function startHold(event) {
      if (event.type === 'mousedown' && event.button !== 0) return;
      holding = true;
      roarBtn.classList.add('holding');
      if (!rafId) rafId = requestAnimationFrame(stepRoar);
    }
    function stopHold() {
      holding = false;
      roarBtn.classList.remove('holding');
    }
    roarBtn.addEventListener('pointerdown', startHold);
    window.addEventListener('pointerup', stopHold);
    roarBtn.addEventListener('keydown', event => {
      if (event.key === ' ' || event.key === 'Enter') startHold(event);
    });
    roarBtn.addEventListener('keyup', stopHold);
    // Single click also boosts +15 dB so tap users get instant gratification
    roarBtn.addEventListener('click', () => {
      db = Math.min(125, Math.max(db + 15, 108));
      renderDb();
      if (!rafId) rafId = requestAnimationFrame(stepRoar);
    });
    renderDb();
  }

